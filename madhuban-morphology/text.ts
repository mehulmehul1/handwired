export type RGB = [number, number, number]

export function drawText(rgba: Uint8Array, w: number, h: number, x0: number, y0: number, text: string, color: RGB = [40, 30, 24], scale = 2) {
  let cx = x0
  for (const ch of text.toUpperCase()) {
    const g = G[ch]
    if (g) {
      for (let ry = 0; ry < 7; ry++) {
        for (let rx = 0; rx < 5; rx++) {
          if (g[ry]![rx] !== '#') continue
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              const px = cx + rx * scale + sx
              const py = y0 + ry * scale + sy
              if (px < 0 || px >= w || py < 0 || py >= h) continue
              const i = (py * w + px) * 4
              rgba[i] = color[0]; rgba[i + 1] = color[1]; rgba[i + 2] = color[2]; rgba[i + 3] = 255
            }
          }
        }
      }
    }
    cx += 6 * scale
  }
}

export function drawTextCentered(rgba: Uint8Array, w: number, h: number, xc: number, y0: number, text: string, color: RGB = [40, 30, 24], scale = 2) {
  drawText(rgba, w, h, Math.round(xc - (text.length * 6 * scale) / 2), y0, text, color, scale)
}
